#!/usr/bin/env python3
"""Generate cpp/src/tables.cpp from python-workflow/midi2nbs.py.

The Python tables are the single source of truth.  Run this after changing
GM_INSTRUMENT_MAPPINGS, GM_PERCUSSION_MAPPINGS, GM_TO_NBS, KIT, GM_TO_SLOT or
GM_DRUM_NAMES:

    python tools/gen_tables.py          # write cpp/src/tables.cpp
    python tools/gen_tables.py --check  # fail if the checked-in file is stale
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY_SOURCE = ROOT / "python-workflow" / "midi2nbs.py"
AGENT_DIR = ROOT / "python-workflow" / "_agent"
OUTPUT = ROOT / "cpp" / "src" / "tables.cpp"


def load_reference():
    sys.path.insert(0, str(AGENT_DIR))
    spec = importlib.util.spec_from_file_location("nyaa_midi2nbs_ref", PY_SOURCE)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {PY_SOURCE}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def q(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_text(ref) -> str:
    out: list[str] = []
    add = out.append

    add("// Generated by tools/gen_tables.py from python-workflow/midi2nbs.py; do not edit.")
    add("// Data sources: u3002 MIT GM mapping / OpenNBS (MIT) midi_instruments.gml.")
    add('#include "midi2nbs.h"')
    add("#include <stdexcept>")
    add("")
    add("namespace nyaa {")
    add("")
    add("const int KEY_LO = 33, KEY_HI = 57;")
    add("")
    add("const GmEntry kInstrumentMap[128] = {")
    items = sorted(ref.GM_INSTRUMENT_MAPPINGS.items())
    for start in range(0, len(items), 3):
        row = ", ".join(f"{{ {q(name)}, {octave:+d} }}" for _, (name, octave) in items[start:start + 3])
        add(f"    {row},")
    add("};")
    add("")
    add("const std::map<int, std::pair<const char*, int>> kPercussionMap = {")
    for gm, (name, key) in sorted(ref.GM_PERCUSSION_MAPPINGS.items()):
        add(f"    {{ {gm}, {{ {q(name)}, {key:+d} }} }},")
    add("};")
    add("")
    add("namespace {")
    add("const std::pair<const char*, const char*> kGmToNbs[] = {")
    for source, target in ref.GM_TO_NBS.items():
        add(f"    {{ {q(source)}, {q(target)} }},")
    add("};")
    add("}  // namespace")
    add("")
    add("const char* gm_to_nbs(const std::string& name) {")
    add("    for (const auto& kv : kGmToNbs)")
    add("        if (name == kv.first) return kv.second;")
    add('    throw std::runtime_error("未知音色: " + name);')
    add("}")
    add("")
    add("const std::vector<DrumSlot>& kit() {")
    add("    static const std::vector<DrumSlot> k = {")
    for slot in ref.KIT:
        add(f"        {{ {q(slot.slot)}, {q(slot.instrument)}, {slot.key}, {slot.times}, {slot.step} }},")
    add("    };")
    add("    return k;")
    add("}")
    add("")
    add("// GM 音高 → 槽位名（按 Python dict 插入序）")
    add("const std::vector<std::pair<int, const char*>> kGmToSlotOrdered = {")
    for gm, slot in ref.GM_TO_SLOT.items():
        add(f"    {{ {gm}, {q(slot)} }},")
    add("};")
    add("")
    add("// GM 鼓名（按 Python dict 插入序）")
    add("const std::vector<std::pair<int, const char*>> kGmDrumNames = {")
    for gm, name in ref.GM_DRUM_NAMES.items():
        add(f"    {{ {gm}, {q(name)} }},")
    add("};")
    add("")
    add("// 音级名")
    add("const char* const kPitchClassName[12] = {")
    add("    " + ", ".join(q(x) for x in ref.PITCH_CLASS_NAME) + "};")
    add("const char* const kPitchClassFlat[12] = {")
    add("    " + ", ".join(q(x) for x in ref.PITCH_CLASS_FLAT) + "};")
    add("")
    add("// GM 音高 → 槽位名")
    add("const std::map<int, const char*> kGmToSlot = {")
    for gm, slot in sorted(ref.GM_TO_SLOT.items()):
        add(f"    {{ {gm}, {q(slot)} }},")
    add("};")
    add("")
    add("}  // namespace nyaa")
    add("")
    return "\n".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="only verify that tables.cpp is current")
    args = parser.parse_args(argv)

    ref = load_reference()
    generated = build_text(ref)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUTPUT.exists() else ""
        if current != generated:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run: python tools/gen_tables.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
